import cv2
import numpy as np
import matplotlib.pyplot as plt

import os

def get_size(filename):
    return os.path.getsize(filename) / 1024

image_path = 'input_image.jpg'
img = cv2.imread("/content/images (1).jpg")

if img is None:
    print(f"Error: Image not found at '{image_path}'. Please upload or provide a valid image.")
else:
    cv2.imwrite('original_saved.jpg', img, [cv2.IMWRITE_JPEG_QUALITY, 100])

    compressed_filename = 'compressed_image.jpg'
    quality = 50
    cv2.imwrite(compressed_filename, img, [cv2.IMWRITE_JPEG_QUALITY, quality])

    # 4. Compare Sizes
    original_size = get_size('original_saved.jpg')
    compressed_size = get_size(compressed_filename)

    print(f"Original Size: {original_size:.2f} KB")
    print(f"Compressed Size (Quality {quality}): {compressed_size:.2f} KB")
    print(f"Space Saved: {original_size - compressed_size:.2f} KB")

    # 5. Visual Comparison
    compressed_img = cv2.imread(compressed_filename)
    plt.figure(figsize=(10, 5))

    plt.subplot(1, 2, 1)
    plt.title("Original Image")
    plt.imshow(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
    plt.axis('off')

    plt.subplot(1, 2, 2)
    plt.title(f"Compressed Image (Quality {quality})")
    plt.imshow(cv2.cvtColor(compressed_img, cv2.COLOR_BGR2RGB))
    plt.axis('off')

    plt.show()